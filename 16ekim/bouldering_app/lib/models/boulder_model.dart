class Boulder {
  final String grade;
  final String holdColor;
  final String locations;
  final int attempts;
  final bool isFlashed;
  final DateTime date;
  final String notes;

  const Boulder({
    required this.grade,
    required this.holdColor,
    required this.locations,
    required this.attempts,
    required this.isFlashed,
    required this.date,
    required this.notes,
  });
}
